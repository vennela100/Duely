const DICTS: Record<Lang, Dict> = { en, hi, te };

export const translate = (lang: Lang, key: string): string =>
  DICTS[lang]?.[key] ?? en[key] ?? key;

// Hook — re-renders when language changes (subscribes to the store).
export const useT = () => {
  const lang = useUIStore((s) => s.lang);
  return useCallback((key: string) => translate(lang, key), [lang]);
};
